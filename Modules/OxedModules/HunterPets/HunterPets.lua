-- The player's look for the box: background, border, portrait, text, size.
-- Sizes change only out of combat (the box is a secure button).
local function StyleIndicator(fade)
    local b, s = indicator, settings
    local k = fade and 0.3 or 1
    b.bg:SetColorTexture(s.bgR or 0, s.bgG or 0, s.bgB or 0, s.bgAlpha or 0.6)
    b.bg:SetAlpha(k)
    b.edge:SetShown(s.border and true or false)
    b.edge:SetAlpha(k)
    local pic = s.showPortrait ~= false
    b.portrait:SetShown(pic)
    b.portrait:SetAlpha(k)
    b.happy:SetAlpha(k)
    local text = s.showText ~= false
    b.name:SetShown(text)
    b.info:SetShown(text)
    b.name:SetAlpha(k)
    b.info:SetAlpha(k)
    local size = s.fontSize or 12
    local font = (GameFontNormal and GameFontNormal:GetFont()) or "Fonts\\FRIZQT__.TTF"
    pcall(b.name.SetFont, b.name, font, size + 1, s.outline and "OUTLINE" or "")
    pcall(b.info.SetFont, b.info, font, size - 1, s.outline and "OUTLINE" or "")
    if not InCombat() then
        local h = math.max(38, size * 2 + 16)
        b.portrait:SetSize(h - 6, h - 6)
        b.name:ClearAllPoints()
        b.info:ClearAllPoints()
        local left = pic and b.portrait or b
        local from = pic and "TOPRIGHT" or "TOPLEFT"
        b.name:SetPoint("TOPLEFT", left, from, pic and 8 or 6, -3)
        b.info:SetPoint("BOTTOMLEFT", left, pic and "BOTTOMRIGHT" or "BOTTOMLEFT", pic and 8 or 6, 4)
        b.name:SetPoint("RIGHT", b, "RIGHT", -4, 0)
        b.info:SetPoint("RIGHT", b, "RIGHT", -4, 0)
        local width = text and (s.width or 170) or (pic and h or 40)
        b:SetSize(width, h)
    end
end

UpdateIndicator = function()
    if not indicator then return end
    local want = running and isHunter and settings and settings.indicator
    -- A secure button can only be shown or hidden out of combat.
    if not InCombat() then
        indicator:SetScale(settings and settings.scale or 1)
        indicator:SetShown(want and true or false)
    end
    if not want then return end

    local out = HasPet()
    if out then
        SetPortraitTexture(indicator.portrait, "pet")
        local name = Plain(UnitName, "pet") or T("Pet")
        indicator.name:SetText(name)
        local lvl = Plain(UnitLevel, "pet")
        local h = Happiness()
        local parts = {}
        if lvl then parts[#parts + 1] = string.format(T("Level %d"), lvl) end
        if PetDead() then
            parts[#parts + 1] = "|cffff4040" .. T("Dead") .. "|r"
        elseif h then
            local c = HAPPY_COLOUR[h]
            parts[#parts + 1] = string.format("|cff%02x%02x%02x%s|r", c[1] * 255, c[2] * 255, c[3] * 255, T(HAPPY_TEXT[h]))
        end
        local loyalty = GetPetLoyalty and Plain(GetPetLoyalty)
        if type(loyalty) == "string" and loyalty ~= "" then parts[#parts + 1] = loyalty end
        indicator.info:SetText(table.concat(parts, "  "))
        if h and HAPPY_COORDS[h] then
            indicator.happy:SetTexCoord(unpack(HAPPY_COORDS[h]))
            indicator.happy:Show()
        else
            indicator.happy:Hide()
        end
        local hungry = settings.glowHungry and h and h <= (settings.remindAt or 2)
        indicator.glow:SetShown(hungry and true or false)
        if hungry then indicator.pulse:Play() else indicator.pulse:Stop() end
        StyleIndicator(settings.hideHappy and h == 3)
    else
        indicator.portrait:SetTexture(ICON)
        indicator.name:SetText(T("No pet"))
        indicator.info:SetText(T("Call Pet or tame one"))
        indicator.happy:Hide()
        indicator.glow:Hide()
        indicator.pulse:Stop()
        StyleIndicator(false)
    end
end

-- ── Tooltip line on tameable beasts ─────────────────────────────────────────

local tooltipHooked = false

local function NpcIDFromUnit(unit)
    local ok, guid = pcall(UnitGUID, unit)
    if not ok or not guid or Secret(guid) then return nil end
    local kind, _, _, _, _, id = strsplit("-", guid)
    if kind ~= "Creature" then return nil end
    return tonumber(id)
end

local function OnUnitTooltip(tt)
    if not (running and settings and settings.tooltip) then return end
    if tt ~= GameTooltip then return end
    local ok, _, unit = pcall(tt.GetUnit, tt)
    if not ok or not unit or Secret(unit) then return end
    local id = NpcIDFromUnit(unit)
    local npc = id and NPCs()[id]
    if not npc then return end
    local lv = npc.min and (npc.max and npc.max ~= npc.min and (npc.min .. "-" .. npc.max) or tostring(npc.min)) or "?"
    local mine = PlayerLevel()
    local colour = (npc.min and npc.min > mine) and "|cffff6060" or "|cff60ff60"
    tt:AddLine(colour .. string.format(T("Tameable %s, level %s"), npc.family or "", lv) .. "|r")
    local list = Teaches(id)
    if list then tt:AddLine(T("Teaches") .. ": " .. table.concat(list, ", "), 0.9, 0.8, 0.5, true) end
end

local function HookTooltip()
    if tooltipHooked then return end
    tooltipHooked = true
    if TooltipDataProcessor and TooltipDataProcessor.AddTooltipPostCall and Enum and Enum.TooltipDataType and Enum.TooltipDataType.Unit then
        TooltipDataProcessor.AddTooltipPostCall(Enum.TooltipDataType.Unit, function(tt)
            pcall(OnUnitTooltip, tt)
        end)
    elseif GameTooltip and GameTooltip.HookScript then
        pcall(GameTooltip.HookScript, GameTooltip, "OnTooltipSetUnit", function(tt) pcall(OnUnitTooltip, tt) tt:Show() end)
    end
end

