local EVENTS = { "UNIT_PET", "UNIT_HAPPINESS", "UNIT_POWER_UPDATE", "PET_UI_UPDATE", "UNIT_LEVEL",
                 "PLAYER_REGEN_ENABLED", "PLAYER_ENTERING_WORLD", "UNIT_HEALTH", "ZONE_CHANGED_NEW_AREA",
                 "PLAYER_LEVEL_UP", "NAME_PLATE_UNIT_ADDED", "UPDATE_MOUSEOVER_UNIT", "PLAYER_TARGET_CHANGED",
                 "UNIT_SPELLCAST_SUCCEEDED" }

events:SetScript("OnEvent", function(_, event, unit, _, spellID)
    if not running then return end
    if event == "UNIT_SPELLCAST_SUCCEEDED" then
        if unit == "player" and not Secret(spellID)
            and (spellID == FEED_PET or SpellName(spellID) == SpellName(FEED_PET)) then
            fedAt = GetTime()
        end
        return
    end
    if event == "NAME_PLATE_UNIT_ADDED" then OnSight(unit) return end
    if event == "UPDATE_MOUSEOVER_UNIT" then OnSight("mouseover") return end
    if event == "PLAYER_TARGET_CHANGED" then OnSight("target") return end
    if event == "PLAYER_REGEN_ENABLED" then
        if settings.indicator and isHunter then BuildIndicator() end
        UpdateIndicator()
        CheckPet()
        return
    end
    if event == "ZONE_CHANGED_NEW_AREA" or event == "PLAYER_LEVEL_UP" then
        if window and window:IsShown() then Refresh() end
        if event == "PLAYER_LEVEL_UP" then return end
    end
    if (event == "UNIT_HEALTH" or event == "UNIT_POWER_UPDATE" or event == "UNIT_HAPPINESS" or event == "UNIT_LEVEL")
        and unit ~= "pet" then return end
    CheckPet()
end)

local ticker

-- Every few seconds: the pet, and a "Nearest" list that follows the player.
local function Tick()
    CheckPet()
    if settings.sort == "near" and (settings.mode == "beasts" or settings.mode == "wish")
        and window and window:IsShown() and not (card and card:IsShown()) then
        Refresh()
    end
end

local function EnsureLists(cfg)
    if type(cfg.wish) ~= "table" then cfg.wish = {} end
    if type(cfg.seen) ~= "table" then cfg.seen = {} end
end

local function Start()
    if running then return end
    running = true
    local _, cls = Plain(UnitClass, "player")
    isHunter = cls == "HUNTER"
    for _, e in ipairs(EVENTS) do pcall(events.RegisterEvent, events, e) end
    HookTooltip()
    placesDirty = true
    if isHunter then
        if settings.indicator then BuildIndicator() end
        if C_Timer.NewTicker then
            ticker = C_Timer.NewTicker(5, Tick)
            markTicker = C_Timer.NewTicker(0.1, UpdateMarks)
        end
        C_Timer.After(8, function() if petWasOut == nil then petWasOut = false end CheckPet() end)
    end
    UpdateIndicator()
end

local function Stop()
    running = false
    events:UnregisterAllEvents()
    if ticker then ticker:Cancel() ticker = nil end
    if markTicker then markTicker:Cancel() markTicker = nil end
    HideMarks(1)
    HideLowWarning()
    if window then window:Hide() end
    UpdateIndicator()
end

