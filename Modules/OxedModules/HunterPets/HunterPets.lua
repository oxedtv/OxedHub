-- npc id -> { "Bite 2", ... }, npc id -> { ability key = true } and
-- npc id -> { { name, rank, pet_level, cost }, ... }, built once.
local teaches, teachKeys, teachInfo
local function BuildTeaches()
    if teaches then return end
    teaches, teachKeys, teachInfo = {}, {}, {}
    for key, ab in pairs(Abilities()) do
        for _, rank in ipairs(ab.ranks or {}) do
            for _, id in ipairs(rank.npc_ids or {}) do
                teaches[id] = teaches[id] or {}
                teachKeys[id] = teachKeys[id] or {}
                teachInfo[id] = teachInfo[id] or {}
                table.insert(teaches[id], ab.name .. " " .. (rank.rank or 1))
                table.insert(teachInfo[id], { name = ab.name, rank = rank.rank or 1, level = rank.pet_level, cost = rank.training_cost })
                teachKeys[id][key] = true
            end
        end
    end
    for _, list in pairs(teaches) do table.sort(list) end
    for _, list in pairs(teachInfo) do
        table.sort(list, function(a, b)
            if a.name ~= b.name then return a.name < b.name end
            return a.rank < b.rank
        end)
    end
end

local function Teaches(id)
    BuildTeaches()
    return teaches[id]
end

-- Beasts per family, and what each family can learn (passives come from the trainer).
local familyCount, familyLearns
local function BuildFamilyFacts()
    if familyCount then return end
    familyCount, familyLearns = {}, {}
    for _, npc in pairs(NPCs()) do
        if npc.family then familyCount[npc.family] = (familyCount[npc.family] or 0) + 1 end
    end
    for _, ab in pairs(Abilities()) do
        if not ab.passive then
            for _, name in ipairs(ab.learned_by or {}) do
                familyLearns[name] = familyLearns[name] or {}
                table.insert(familyLearns[name], ab.name)
            end
        end
    end
    for _, names in pairs(familyLearns) do table.sort(names) end
end

-- How many beasts teach any rank of this ability.
local function TeacherCount(ab)
    local seen, n = {}, 0
    for _, rank in ipairs(ab.ranks or {}) do
        for _, id in ipairs(rank.npc_ids or {}) do
            if not seen[id] then seen[id] = true n = n + 1 end
        end
    end
    return n
end

local function ZoneText(npc)
    local names, seen = {}, {}
    for mapID in pairs(npc.maps or {}) do
        local n = MapName(mapID)
        if n and not seen[n] then seen[n] = true names[#names + 1] = n end
    end
    if npc.map then
        local n = MapName(npc.map)
        if n and not seen[n] then seen[n] = true names[#names + 1] = n end
    end
    if #names == 0 then
        for _, area in ipairs(npc.zones or {}) do
            local n = AreaName(area)
            if n and not seen[n] then seen[n] = true names[#names + 1] = n end
        end
    end
    table.sort(names)
    return table.concat(names, ", ")
end

-- Best spot for a pin: on the player's map, the point nearest the player.
local function BestSpot(npc)
    local here = PlayerMap()
    local maps = npc.maps or {}
    local mapID = (here and maps[here]) and here or nil
    if not mapID then
        for id in pairs(maps) do mapID = id break end
    end
    if not mapID then return npc.map, nil end
    local pts = Points(maps[mapID])
    if #pts == 0 then return mapID, nil end
    local best = pts[1]
    if mapID == here then
        local _, px, py = PlayerSpot()
        if px then
            local bd
            for _, p in ipairs(pts) do
                local d = (p.x - px) ^ 2 + (p.y - py) ^ 2
                if not bd or d < bd then bd, best = d, p end
            end
        end
    end
    return mapID, best
end

local function SetPin(mapID, x, y, label)
    if not (mapID and x and C_Map and C_Map.SetUserWaypoint and UiMapPoint) then
        Say(T("No map spot is known for that one."))
        return
    end
    local ok = pcall(function()
        C_Map.SetUserWaypoint(UiMapPoint.CreateFromCoordinates(mapID, x, y))
        if C_SuperTrack and C_SuperTrack.SetSuperTrackedUserWaypoint then
            C_SuperTrack.SetSuperTrackedUserWaypoint(true)
        end
    end)
    if ok then
        Say(string.format(T("Map pin set: %s, %s %.1f %.1f"), label or "", MapName(mapID) or "", x * 100, y * 100))
    end
end

