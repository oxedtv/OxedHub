    end
    local zoom = Minimap.GetZoom and Plain(Minimap.GetZoom, Minimap) or 0
    local indoors = IsIndoors and Plain(IsIndoors)
    local across = (indoors and INDOOR_YARDS or OUTDOOR_YARDS)[zoom] or OUTDOOR_YARDS[0]
