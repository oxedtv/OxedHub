local ALERT_GAP, SEEN_GAP = 300, 60  -- seconds, per beast
local alertAt, seenAt = {}, {}

-- A beast showed up on a nameplate, under the mouse or as the target: note
-- where, and speak up if it is on the wishlist.
local function OnSight(unit)
    if not (running and isHunter and settings) then return end
    local id = NpcIDFromUnit(unit)
    local npc = id and NPCs()[id]
    if not npc then return end
    if Plain(UnitIsDead, unit) then return end
    local now = GetTime()
    if settings.seen and (not seenAt[id] or now - seenAt[id] >= SEEN_GAP) then
        seenAt[id] = now
        local mapID, x, y = PlayerSpot()
        if mapID then settings.seen[id] = { t = time(), m = mapID, x = x, y = y } end
    end
    if settings.wishAlert and Wished(id) and (not alertAt[id] or now - alertAt[id] >= ALERT_GAP) then
        alertAt[id] = now
        Alert(string.format(T("Wishlist: %s is near you, level %s."), npc.name or "?", LevelText(npc)))
    end
end

