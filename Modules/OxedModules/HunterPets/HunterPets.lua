Refresh = function()
    if not (window and window:IsShown() and settings) then return end
    local mode = settings.mode
    if mode == "trainers" then
        BuildTrainerList()
    elseif mode == "families" then
        BuildFamilyList()
    elseif mode == "abilities" then
        BuildAbilityList()
    else
        BuildBeastList()
    end
    local n = VisibleRows()
    if offset > math.max(0, #list - n) then offset = math.max(0, #list - n) end
    for i = 1, n do
        local e = list[offset + i]
