local function FamilyChoices()
    local out = { "any" }
    for name in pairs(Families()) do out[#out + 1] = name end
    table.sort(out, function(a, b) if a == "any" then return true elseif b == "any" then return false end return a < b end)
    return out
end

local function AbilityChoices()
    local out = { "any" }
    local names = {}
    for key, ab in pairs(Abilities()) do
        if ab.ranks and ab.ranks[1] and not ab.passive then names[#names + 1] = key end
    end
    table.sort(names, function(a, b) return Abilities()[a].name < Abilities()[b].name end)
    for _, k in ipairs(names) do out[#out + 1] = k end
    return out
end

local function BuildBeastList()
    wipe(list)
    BuildTeaches()
    local mine = PlayerLevel()
    local here = PlayerMap()
    local s = search:lower()
    for id, npc in pairs(NPCs()) do
        local ok = true
        if settings.family ~= "any" and npc.family ~= settings.family then ok = false end
        if ok and settings.ability ~= "any" and not (teachKeys[id] and teachKeys[id][settings.ability]) then ok = false end
        if ok and settings.scope == "level" then
            local lo = npc.min or 0
            if lo > mine or lo < mine - 12 then ok = false end
        end
        if ok and settings.zoneOnly then
            if not (here and ((npc.maps and npc.maps[here]) or npc.map == here)) then ok = false end
        end
        if ok and s ~= "" then
            local hay = ((npc.name or "") .. " " .. (npc.family or "")):lower()
            if not hay:find(s, 1, true) then ok = false end
        end
        if ok then list[#list + 1] = { id = id, npc = npc } end
    end
    table.sort(list, function(a, b)
        local la, lb = a.npc.min or 0, b.npc.min or 0
        if la ~= lb then return la > lb end
        return (a.npc.name or "") < (b.npc.name or "")
    end)
end

local function BuildTrainerList()
    wipe(list)
    local side = PlayerSide()
    for id, t in pairs(Trainers()) do
        if t.side == "both" or not side or t.side == side then list[#list + 1] = { id = id, trainer = t } end
    end
    table.sort(list, function(a, b) return (a.trainer.zone or "") < (b.trainer.zone or "") end)
end

local function VisibleRows() return math.floor((H - 150) / ROW_H) end

local function FillRow(row, entry)
    row.entry = entry
    if entry.npc then
        local npc = entry.npc
        local fam = Families()[npc.family or ""]
        row.icon:SetTexture(fam and fam.icon or ICON)
        local nameColour = (npc.class == "Rare" or npc.class == "Rare Elite") and "|cff4fa3ff" or (npc.class == "Elite" and "|cffffd100" or "|cffffffff")
        local lv = npc.min and (npc.max and npc.max ~= npc.min and (npc.min .. "-" .. npc.max) or tostring(npc.min)) or "?"
        local tag = npc.class and ("  |cffaaaaaa" .. T(npc.class) .. "|r") or ""
        row.title:SetText(nameColour .. (npc.name or "?") .. "|r  |cffcccccc" .. T("Level") .. " " .. lv .. "  " .. (npc.family or "") .. "|r" .. tag)
        local teach = Teaches(entry.id)
        local where = ZoneText(npc)
        local line = (where ~= "" and where or T("Zone unknown"))
        if fam and fam.foods then line = line .. "  |cff999999" .. T("Eats") .. ": " .. table.concat(fam.foods, ", ") .. "|r" end
        if teach then line = line .. "  |cffe6cc80" .. table.concat(teach, ", ") .. "|r" end
        row.sub:SetText(line)
        local hasSpot = (npc.maps and next(npc.maps)) and true or false
        row.map:SetEnabled(hasSpot)
    else
        local t = entry.trainer
        row.icon:SetTexture("Interface\\Icons\\Ability_Hunter_BeastTraining")
        row.title:SetText("|cffffffff" .. (t.name or "?") .. "|r  |cffcccccc" .. T("Pet Trainer") .. "|r")
        local c = t.coords and t.coords[1]
        row.sub:SetText((t.zone or "") .. (c and string.format("  %.1f, %.1f", c.x, c.y) or ""))
        row.map:SetEnabled(c and t.ui_map_id and true or false)
    end
    row:Show()
end

Refresh = function()
    if not (window and window:IsShown() and settings) then return end
    if settings.mode == "trainers" then BuildTrainerList() else BuildBeastList() end
    local n = VisibleRows()
    if offset > math.max(0, #list - n) then offset = math.max(0, #list - n) end
    for i = 1, n do
        local e = list[offset + i]
        if e then FillRow(rows[i], e) else rows[i]:Hide() end
    end
    local beasts = settings.mode ~= "trainers"
    window.family:SetShown(beasts)
    window.ability:SetShown(beasts)
    window.scope:SetShown(beasts)
    window.zone:SetShown(beasts)
    window.search:SetShown(beasts)
    window.modeBtn:SetText(beasts and T("Trainers") or T("Beasts"))
    window.family:SetText(settings.family == "any" and T("Any family") or settings.family)
    local ab = Abilities()[settings.ability]
    window.ability:SetText(ab and ab.name or T("Any ability"))
    window.scope:SetText(settings.scope == "level" and T("My level") or T("All levels"))
    window.zone:SetText(settings.zoneOnly and T("This zone") or T("Every zone"))
    if #list == 0 then
        window.summary:SetText(T("Nothing matches. Try All levels or Every zone."))
    else
        window.summary:SetText(string.format(T("%d-%d of %d"), offset + 1, math.min(#list, offset + n), #list))
    end
    if window.bar then
        local top = math.max(0, #list - n)
        window.syncing = true
        window.bar:SetMinMaxValues(0, top)
        window.bar:SetValue(offset)
        window.syncing = false
        window.bar:SetShown(top > 0)
    end
end

local function Step(choices, current, back)
    local idx = 1
    for i, v in ipairs(choices) do if v == current then idx = i break end end
    idx = idx + (back and -1 or 1)
    if idx < 1 then idx = #choices elseif idx > #choices then idx = 1 end
    return choices[idx]
end

