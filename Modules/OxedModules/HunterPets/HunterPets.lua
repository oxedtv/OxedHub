-- Map points are packed 3 characters per point (x, y in 0.2 % steps).
local PACK = "ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789+/"
local packValue = {}
for i = 1, #PACK do packValue[PACK:byte(i)] = i - 1 end

local function Points(packed)
    local list = {}
    if type(packed) ~= "string" then return list end
    for i = 1, #packed - 2, 3 do
        local a, b, c = packed:byte(i, i + 2)
        local va, vb, vc = packValue[a], packValue[b], packValue[c]
        if va and vb and vc then
            local n = va * 4096 + vb * 64 + vc
            list[#list + 1] = { x = math.floor(n / 501) / 500, y = (n % 501) / 500 }
        end
    end
    return list
end

-- npc id -> { "Bite 2", ... } and npc id -> { ability key = true }, built once.
local teaches, teachKeys
local function BuildTeaches()
    if teaches then return end
    teaches, teachKeys = {}, {}
    for key, ab in pairs(Abilities()) do
        for _, rank in ipairs(ab.ranks or {}) do
            for _, id in ipairs(rank.npc_ids or {}) do
                teaches[id] = teaches[id] or {}
                teachKeys[id] = teachKeys[id] or {}
                table.insert(teaches[id], ab.name .. " " .. (rank.rank or 1))
                teachKeys[id][key] = true
            end
        end
    end
    for _, list in pairs(teaches) do table.sort(list) end
end

local function Teaches(id)
    BuildTeaches()
    return teaches[id]
end

local function ZoneText(npc)
    local names, seen = {}, {}
    for mapID in pairs(npc.maps or {}) do
        local n = MapName(mapID)
        if n and not seen[n] then seen[n] = true names[#names + 1] = n end
    end
    if npc.map then
        local n = MapName(npc.map)
        if n and not seen[n] then seen[n] = true names[#names + 1] = n end
    end
    if #names == 0 then
        for _, area in ipairs(npc.zones or {}) do
            local n = AreaName(area)
            if n and not seen[n] then seen[n] = true names[#names + 1] = n end
        end
    end
    table.sort(names)
    return table.concat(names, ", ")
end

-- Best spot for a pin: on the player's map, the point nearest the player.
local function BestSpot(npc)
    local here = PlayerMap()
    local maps = npc.maps or {}
    local mapID = (here and maps[here]) and here or nil
    if not mapID then
        for id in pairs(maps) do mapID = id break end
    end
    if not mapID then return npc.map, nil end
    local pts = Points(maps[mapID])
    if #pts == 0 then return mapID, nil end
    local best = pts[1]
    if mapID == here and C_Map.GetPlayerMapPosition then
        local pos = Plain(C_Map.GetPlayerMapPosition, here, "player")
        local px, py
        if pos and pos.GetXY then
            local ok, a, b = pcall(pos.GetXY, pos)
            if ok and not Secret(a) and not Secret(b) then px, py = a, b end
        end
        if px then
            local bd
            for _, p in ipairs(pts) do
                local d = (p.x - px) ^ 2 + (p.y - py) ^ 2
                if not bd or d < bd then bd, best = d, p end
            end
        end
    end
    return mapID, best
end

local function SetPin(mapID, x, y, label)
    if not (mapID and x and C_Map and C_Map.SetUserWaypoint and UiMapPoint) then
        Say(T("No map spot is known for that one."))
        return
    end
    local ok = pcall(function()
        C_Map.SetUserWaypoint(UiMapPoint.CreateFromCoordinates(mapID, x, y))
        if C_SuperTrack and C_SuperTrack.SetSuperTrackedUserWaypoint then
            C_SuperTrack.SetSuperTrackedUserWaypoint(true)
        end
    end)
    if ok then
        Say(string.format(T("Map pin set: %s, %s %.1f %.1f"), label or "", MapName(mapID) or "", x * 100, y * 100))
    end
end

-- ── Reminders ───────────────────────────────────────────────────────────────

local lastHappy, lastRemind, petWasOut, deathSaid = nil, 0, nil, false
local noPetSaidAt = 0

local function Alert(text)
    if not settings then return end
    if settings.remindChat then Say(text) end
    if settings.remindScreen and RaidNotice_AddMessage and RaidWarningFrame and ChatTypeInfo then
        pcall(RaidNotice_AddMessage, RaidWarningFrame, text, ChatTypeInfo["RAID_WARNING"])
    end
    local API = OxedHub.ModuleAPI
    if not (API and API:PlaySound(settings.sound)) then
        if PlaySound and SOUNDKIT and SOUNDKIT.RAID_WARNING then pcall(PlaySound, SOUNDKIT.RAID_WARNING, "Master") end
    end
end

local function FoodText()
    if not GetPetFoodTypes then return nil end
    local ok, a, b, c, d, e, f = pcall(GetPetFoodTypes)
    if not ok then return nil end
    local list = {}
    for _, v in ipairs({ a, b, c, d, e, f }) do
        if type(v) == "string" and not Secret(v) then list[#list + 1] = v end
    end
    return #list > 0 and table.concat(list, ", ") or nil
end

local function CheckPet()
    if not (running and isHunter and settings) then return end
    local out = HasPet()
    if out == nil then return end

    if out then
        petWasOut, noPetSaidAt = true, 0
        local dead = PetDead()
        if dead and settings.petDied and not deathSaid then
            deathSaid = true
            Alert(T("Your pet has died. Revive Pet."))
        elseif dead == false then
            deathSaid = false
        end

        local h = Happiness()
        if h and not dead then
            local now = GetTime()
            local dropped = lastHappy and h < lastHappy
            if h <= (settings.remindAt or 2) then
                local gap = (settings.repeatMin or 5) * 60
                if dropped or (gap > 0 and now - lastRemind >= gap and not InCombat()) then
                    lastRemind = now
                    local food = FoodText()
                    local text = h == 1 and T("Your pet is unhappy. Feed it now.") or T("Your pet is getting hungry. Feed it.")
                    if food then text = text .. " (" .. food .. ")" end
                    Alert(text)
                end
            else
                lastRemind = 0
            end
            lastHappy = h
        end
    else
        lastHappy, deathSaid = nil, false
        if settings.noPet and not InCombat() and PlayerLevel() >= 10 then
            local now = GetTime()
            if now - noPetSaidAt > 300 then
                noPetSaidAt = now
                -- Not on login straight away: the pet takes a moment to come back.
                if petWasOut ~= nil then Alert(T("No pet out. Call Pet.")) end
            end
        end
        petWasOut = false
    end
    if UpdateIndicator then UpdateIndicator() end
end

