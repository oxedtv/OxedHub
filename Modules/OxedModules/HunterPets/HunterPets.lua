local function UpdateMarks()
    if not (running and isHunter and settings and settings.wishMinimap and settings.wish and next(settings.wish)) then
        HideMarks(1)
        return
    end
    local cont, wx, wy = PlayerWorld()
    if not cont or (IsInInstance and Plain(IsInInstance)) then HideMarks(1) return end
    if placesDirty or cont ~= placesCont then RebuildPlaces(cont) end
    local radius = MinimapRadius()
    local width = Minimap:GetWidth()
    if #places == 0 or not (radius and radius > 0 and width and width > 0) then HideMarks(1) return end

    local perYard = (width / 2) / radius
    local spin = ((C_CVar and C_CVar.GetCVar and C_CVar.GetCVar("rotateMinimap")) or (GetCVar and GetCVar("rotateMinimap"))) == "1"
    local sinF, cosF = 0, 1
    if spin then
        local facing = GetPlayerFacing and Plain(GetPlayerFacing)
        if not facing then HideMarks(1) return end
        sinF, cosF = math.sin(facing), math.cos(facing)
    end
    local square = GetMinimapShape and GetMinimapShape() == "SQUARE"
    local reach = radius - (MARK_SIZE / 2) / perYard

    local n = 0
    for _, pl in ipairs(places) do
        -- World Y grows to the west and world X to the north.
        local east, north = wy - pl.wy, pl.wx - wx
        local x, y = east, north
        if spin then x, y = east * cosF + north * sinF, north * cosF - east * sinF end
        local inside
        if square then
            inside = math.abs(x) <= reach and math.abs(y) <= reach
        else
            inside = x * x + y * y <= reach * reach
        end
        if inside then
            n = n + 1
            local m = MarkAt(n)
            if m.place ~= pl then
                m.place = pl
                local fam = Families()[pl.npc.family or ""]
                m.icon:SetTexture(fam and fam.icon or ICON)
            end
            m:ClearAllPoints()
            m:SetPoint("CENTER", Minimap, "CENTER", x * perYard, y * perYard)
            m:Show()
            if n >= MARK_MAX then break end
        end
    end
    if n < marksShown then HideMarks(n + 1) end
    marksShown = n
end

