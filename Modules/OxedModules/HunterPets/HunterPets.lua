    end
    add(T("Level"), LevelText(npc) .. (npc.class and (", " .. T(npc.class)) or "") .. tameNote)
    if type(npc.speed) == "number" then add(T("Attack speed"), string.format(T("%.1f s"), npc.speed)) end
    if fam and fam.foods then add(T("Eats"), table.concat(fam.foods, ", ")) end
    local seen = settings.seen and settings.seen[id]
    if seen then add(T("Seen by you"), AgoText(seen.t) .. ", " .. (MapName(seen.m) or "?")) end
    local info = teachInfo[id]
    if info then
        lines[#lines + 1] = gold .. T("Teaches") .. ":|r"
        for _, t in ipairs(info) do
            local bits = {}
            if t.level then bits[#bits + 1] = string.format(T("pet level %d"), t.level) end
            if t.cost then bits[#bits + 1] = string.format(T("%d training points"), t.cost) end
            lines[#lines + 1] = "  " .. t.name .. " " .. t.rank
                .. (#bits > 0 and ("  |cff999999" .. table.concat(bits, ", ") .. "|r") or "")
        end
    else
        lines[#lines + 1] = "|cff999999" .. T("Teaches nothing when tamed.") .. "|r"
    end
    return table.concat(lines, "\n")
end

ShowCard = function(id)
    local npc = NPCs()[id]
    if not (npc and settings) then return end
    BuildWindow()
    BuildCard()
    if not window:IsShown() then window:Show() end
    window.search:ClearFocus()
    local c = card
    c.id, c.npc = id, npc
    c:Show()
    c.name:SetText(npc.name or "?")
    PaintStar(c.star, Wished(id))
    c.info:SetText(CardText(id, npc))
    ShowModel(c.modelBox, id, npc)
    c.modelHint:SetShown(settings.models ~= false)

    -- Zones with points: the player's own first, then the busiest.
    local here = PlayerMap()
    local order = {}
    for mapID, packed in pairs(npc.maps or {}) do
        order[#order + 1] = { id = mapID, n = math.floor(#packed / 3) }
    end
    table.sort(order, function(a, b)
        if (a.id == here) ~= (b.id == here) then return a.id == here end
        if a.n ~= b.n then return a.n > b.n end
        return a.id < b.id
    end)
    c.pin:SetEnabled(#order > 0)
    for i, b in ipairs(c.zones) do
        local z = order[i]
        if z then
            b.mapID = z.id
            b:SetText((MapName(z.id) or "?") .. "  (" .. z.n .. ")")
            b:Show()
        else
            b.mapID = nil
            b:Hide()
        end
    end
    local where = ""
    if #order == 0 then
        where = ZoneText(npc)
        if where == "" then where = T("Zone unknown") end
    end
    c.whereText:SetText(where)
    DrawCardMap(id, npc, order[1] and order[1].id or nil)
end

