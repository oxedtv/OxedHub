local function AgoText(stamp)
    local s = math.max(0, time() - (stamp or 0))
    if s < 3600 then return string.format(T("%d min ago"), math.max(1, math.floor(s / 60))) end
    if s < 86400 then return string.format(T("%d h ago"), math.floor(s / 3600)) end
    return string.format(T("%d days ago"), math.floor(s / 86400))
end

-- Lay the zone's own map art over the canvas. A tile on the last row or column
-- runs past the map's edge, so it is cropped instead of hanging out.
local function DrawZoneArt(canvas, mapID)
    for _, tile in ipairs(canvas.tiles) do tile:Hide() end
    if not (mapID and C_Map.GetMapArtLayers and C_Map.GetMapArtLayerTextures) then return end
    local layers = Plain(C_Map.GetMapArtLayers, mapID)
    local layer = layers and layers[1]
    local files = layer and Plain(C_Map.GetMapArtLayerTextures, mapID, 1)
    if not files then return end
    local layerW, layerH, tileW, tileH = layer.layerWidth, layer.layerHeight, layer.tileWidth, layer.tileHeight
    if not (layerW and layerH and tileW and tileH and layerW > 0 and layerH > 0 and tileW > 0 and tileH > 0) then return end
    local cols = math.ceil(layerW / tileW)
    local scaleX, scaleY = canvas:GetWidth() / layerW, canvas:GetHeight() / layerH
    for i, file in ipairs(files) do
        local col, row = (i - 1) % cols, math.floor((i - 1) / cols)
        local w = math.min(tileW, layerW - col * tileW)
        local h = math.min(tileH, layerH - row * tileH)
        if w > 0 and h > 0 then
            local tile = canvas.tiles[i]
            if not tile then
                tile = canvas:CreateTexture(nil, "ARTWORK")
                canvas.tiles[i] = tile
            end
            tile:SetTexture(file)
            tile:SetTexCoord(0, w / tileW, 0, h / tileH)
            tile:SetSize(w * scaleX, h * scaleY)
            tile:ClearAllPoints()
            tile:SetPoint("TOPLEFT", canvas, "TOPLEFT", col * tileW * scaleX, -row * tileH * scaleY)
            tile:Show()
        end
    end
end

local function PlaceDot(canvas, i, x, y, r, g, b, size)
    local dot = canvas.dots[i]
    if not dot then
        dot = canvas:CreateTexture(nil, "OVERLAY")
        dot:SetTexture(DISC)
        canvas.dots[i] = dot
    end
    dot:SetVertexColor(r, g, b, 1)
    dot:SetSize(size, size)
    dot:ClearAllPoints()
    dot:SetPoint("CENTER", canvas, "TOPLEFT", x * canvas:GetWidth(), -y * canvas:GetHeight())
    dot:Show()
end

-- One zone on the card's map: gold for known spots, green where you saw it,
-- white for you.
local function DrawCardMap(id, npc, mapID)
    local c = card.canvas
    c.mapID, c.label = mapID, npc.name
    DrawZoneArt(c, mapID)
    c.points = Points(npc.maps and npc.maps[mapID])
    local n = #c.points
    for i, p in ipairs(c.points) do PlaceDot(c, i, p.x, p.y, 1, 0.82, 0, 7) end
    local seen = settings.seen and settings.seen[id]
    if seen and seen.m == mapID then
        n = n + 1
        PlaceDot(c, n, seen.x, seen.y, 0.3, 1, 0.3, 8)
    end
    local here, px, py = PlayerSpot()
    if here == mapID then
        n = n + 1
        PlaceDot(c, n, px, py, 1, 1, 1, 9)
    end
    for i = n + 1, #c.dots do c.dots[i]:Hide() end
    for _, b in ipairs(card.zones) do b:SetActive(b.mapID == mapID) end
    c.msg:SetShown(mapID == nil)
end

local function ApplyCamera(h)
    local m = h.model
    pcall(m.SetPortraitZoom, m, 0)
    pcall(m.SetCamDistanceScale, m, h.zoom)
    pcall(m.SetFacing, m, h.facing)
end

local function BuildModelBox(parent)
    local h = CreateFrame("Frame", nil, parent)
    h:SetSize(210, 214)
    local bg = h:CreateTexture(nil, "BACKGROUND")
    bg:SetAllPoints()
    bg:SetColorTexture(1, 1, 1, 0.05)
    h.icon = h:CreateTexture(nil, "ARTWORK")
    h.icon:SetSize(72, 72)
    h.icon:SetPoint("CENTER")
    h.icon:SetTexCoord(0.08, 0.92, 0.08, 0.92)
    local ok, m = pcall(CreateFrame, "PlayerModel", nil, h)
    if ok and m then
        h.model = m
        m:SetAllPoints()
        m:EnableMouse(false)  -- the box below takes the drag and the wheel
    end
    h.facing, h.zoom = -0.5, 1
    h:EnableMouse(true)
    h:EnableMouseWheel(true)
    h:SetScript("OnMouseDown", function(self)
        self.dragging, self.lastX = true, (GetCursorPosition())
    end)
    h:SetScript("OnMouseUp", function(self) self.dragging = false end)
    h:SetScript("OnHide", function(self) self.dragging, self.checkUntil = false, nil end)
    h:SetScript("OnMouseWheel", function(self, delta)
        self.zoom = math.max(0.5, math.min(2.5, self.zoom - delta * 0.1))
        if self.model then pcall(self.model.SetCamDistanceScale, self.model, self.zoom) end
    end)
    h:SetScript("OnUpdate", function(self)
        local model = self.model
        if not model then return end
        -- The icon waits underneath until the model has really arrived.
        if self.checkUntil then
            local fine, file = pcall(model.GetModelFileID, model)
            if fine and file and not Secret(file) and file ~= 0 then
                self.checkUntil = nil
                self.icon:Hide()
                ApplyCamera(self)
            elseif GetTime() > self.checkUntil then
                self.checkUntil = nil
            end
        end
        if self.dragging then
            local x = GetCursorPosition()
            self.facing = self.facing + (x - (self.lastX or x)) * 0.012
            self.lastX = x
            pcall(model.SetFacing, model, self.facing)
        end
    end)
    return h
end

