-- ── Beast data ──────────────────────────────────────────────────────────────

-- Map points are packed 3 characters per point (x, y in 0.2 % steps).
local PACK = "ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789+/"
local packValue = {}
for i = 1, #PACK do packValue[PACK:byte(i)] = i - 1 end

local function Points(packed)
    local list = {}
    if type(packed) ~= "string" then return list end
    for i = 1, #packed - 2, 3 do
        local a, b, c = packed:byte(i, i + 2)
        local va, vb, vc = packValue[a], packValue[b], packValue[c]
        if va and vb and vc then
            local n = va * 4096 + vb * 64 + vc
            list[#list + 1] = { x = math.floor(n / 501) / 500, y = (n % 501) / 500 }
        end
    end
    return list
end

-- ── Where things are, in yards ──────────────────────────────────────────────

-- A zone map is a plain rectangle of the world: world X follows the map's y and
-- world Y its x, so two corners give every point. Kept per map, so a whole
-- bestiary can be measured without asking the game once per point.
local mapCorners = {}
local function CornersOf(mapID)
    local c = mapCorners[mapID]
    if c ~= nil then return c or nil end
    c = false
    if C_Map and C_Map.GetWorldPosFromMapPos and CreateVector2D then
        local cont, a = Plain(C_Map.GetWorldPosFromMapPos, mapID, CreateVector2D(0, 0))
        local _, b = Plain(C_Map.GetWorldPosFromMapPos, mapID, CreateVector2D(1, 1))
        if cont and a and b and a.GetXY and b.GetXY then
            local ok, ax, ay, bx, by = pcall(function()
                local x1, y1 = a:GetXY()
                local x2, y2 = b:GetXY()
                return x1, y1, x2, y2
            end)
            if ok and type(ax) == "number" and type(ay) == "number" and type(bx) == "number" and type(by) == "number"
                and not (Secret(ax) or Secret(ay) or Secret(bx) or Secret(by)) then
                c = { cont = cont, ax = ax, ay = ay, sx = bx - ax, sy = by - ay }
            end
        end
    end
    mapCorners[mapID] = c
    return c or nil
end

-- The player's map and position on it (0-1), or nil (instances, loading).
local function PlayerSpot()
    local mapID = PlayerMap()
    if not (mapID and C_Map.GetPlayerMapPosition) then return nil end
    local pos = Plain(C_Map.GetPlayerMapPosition, mapID, "player")
    if not (pos and pos.GetXY) then return nil end
    local ok, x, y = pcall(pos.GetXY, pos)
    if not ok or Secret(x) or Secret(y) or not x or not y or (x == 0 and y == 0) then return nil end
    return mapID, x, y
end

-- Continent and world yards of the player, or nil.
local function PlayerWorld()
    local mapID, x, y = PlayerSpot()
    local c = mapID and CornersOf(mapID)
    if not c then return nil end
    return c.cont, c.ax + c.sx * y, c.ay + c.sy * x
end

-- Yards to the beast's nearest known point on this continent, or nil. Reads
-- the packed points directly: this runs over every beast on each re-sort.
local function YardsTo(npc, cont, wx, wy)
    local best
    for mapID, packed in pairs(npc.maps or {}) do
        local c = CornersOf(mapID)
        if c and c.cont == cont and type(packed) == "string" then
            for i = 1, #packed - 2, 3 do
                local p1, p2, p3 = packed:byte(i, i + 2)
                local v1, v2, v3 = packValue[p1], packValue[p2], packValue[p3]
                if v1 and v2 and v3 then
                    local n = v1 * 4096 + v2 * 64 + v3
                    local dx = c.ax + c.sx * ((n % 501) / 500) - wx
                    local dy = c.ay + c.sy * (math.floor(n / 501) / 500) - wy
                    local d = dx * dx + dy * dy
                    if not best or d < best then best = d end
                end
            end
        end
    end
    return best and math.sqrt(best) or nil
end

local function YardsText(d)
    if d < 1000 then return string.format(T("%d yd"), math.floor(d / 10 + 0.5) * 10) end
    return string.format(T("%.1fk yd"), d / 1000)
end

