-- While a pet is called or dismissed its happiness can read wrong for a moment,
-- and it stays low for the 20 seconds a pet takes to eat. So a reading has to
-- last HAPPY_HOLD before it counts, and nothing asks for food just after a meal.
local HAPPY_HOLD, FED_QUIET = 6, 30
local FEED_PET, DISMISS_PET = 6991, 2641
local heldHappy, heldSince, fedAt = nil, 0, 0

local function DismissingPet()
    local name = UnitCastingInfo and Plain(UnitCastingInfo, "player")
    return name ~= nil and name == SpellName(DISMISS_PET)
end

local function FeedReminder(h)
    local now = GetTime()
    if h ~= heldHappy then
        heldHappy, heldSince = h, now
        return
    end
    if now - heldSince < HAPPY_HOLD then return end

    local dropped = lastHappy and h < lastHappy
    lastHappy = h
    if h > (settings.remindAt or 2) then
        lastRemind = 0
        return
    end
    if now - fedAt < FED_QUIET or DismissingPet() then return end

    local gap = (settings.repeatMin or 5) * 60
    if dropped or (gap > 0 and now - lastRemind >= gap and not InCombat()) then
        lastRemind = now
        local food = FoodText()
        local text = h == 1 and T("Your pet is unhappy. Feed it now.") or T("Your pet is getting hungry. Feed it.")
        if food then text = text .. " (" .. food .. ")" end
        Alert(text)
    end
end

-- Once per dip, only in a fight: a revived pet starts low and that is no news.
-- It re-arms once health is back above the line by LOW_REARM, so healing that
-- hovers around the line does not repeat the alert.
local LOW_REARM, LOW_REFIRE = 10, 15
local lowArmed, lowSaidAt = true, 0

local function HealthPercent()
    local cur = Plain(UnitHealth, "pet")
    local max = Plain(UnitHealthMax, "pet")
    if type(cur) ~= "number" or type(max) ~= "number" or max <= 0 then return nil end
    return cur / max * 100
end

-- In a fight the pet's health can be a secret: Lua cannot compare it, so it
-- cannot choose to alert or play a sound. (Heartbeat falls back on Blizzard's
-- LowHealthFrame, but that follows the player only.) The game can still do the
-- comparing: a step curve turns health into alpha 1 below the line and 0 above,
-- and SetAlpha takes the secret. Nothing here may animate this frame's alpha.
local lowWarning, lowCurve, lowCurveAt

local function HideLowWarning()
    if lowWarning then lowWarning:Hide() end
end

local function LowCurve()
    local at = settings.lowHealthAt or 30
    if lowCurve and lowCurveAt == at then return lowCurve end
    if not (C_CurveUtil and C_CurveUtil.CreateCurve and Enum and Enum.LuaCurveType) then return nil end
    local ok, curve = pcall(function()
        local c = C_CurveUtil.CreateCurve()
        c:SetType(Enum.LuaCurveType.Step)
        c:AddPoint(0, 0)         -- dead: the death alert covers that
        c:AddPoint(0.001, 1)
        c:AddPoint(at / 100, 0)
        return c
    end)
    if not ok then return nil end
    lowCurve, lowCurveAt = curve, at
    return curve
end

local function ShowSecretLow()
    local curve = settings.remindScreen and InCombat() and UnitHealthPercent
        and CurveConstants and CurveConstants.ScaleTo100 and LowCurve()
    if not curve then HideLowWarning() return end
    if not lowWarning then
        lowWarning = CreateFrame("Frame", "OxedHubHunterPetsLowHealth", UIParent)
        lowWarning:SetSize(420, 40)
        lowWarning:SetPoint("CENTER", UIParent, "CENTER", 0, 200)
        lowWarning:SetFrameStrata("HIGH")
        lowWarning:SetAlpha(0)
        lowWarning.text = lowWarning:CreateFontString(nil, "OVERLAY", "GameFontNormalHuge")
        lowWarning.text:SetPoint("CENTER")
        lowWarning.text:SetTextColor(1, 0.25, 0.25)
        lowWarning:Hide()
    end
    local ok = pcall(function()
        lowWarning:SetAlpha(UnitHealthPercent("pet", true, curve))
        lowWarning.text:SetFormattedText(T("Pet low on health: %d%%"), UnitHealthPercent("pet", true, CurveConstants.ScaleTo100))
    end)
    if ok then lowWarning:Show() else lowWarning:Hide() end
end

local function HealthReminder(dead)
    if dead then
        lowArmed = true
        HideLowWarning()
        return
    end
    if not settings.lowHealth then HideLowWarning() return end
    local pct = HealthPercent()
    if not pct then ShowSecretLow() return end
    HideLowWarning()
    local at = settings.lowHealthAt or 30
    if pct >= at + LOW_REARM then
        lowArmed = true
    elseif pct > 0 and pct <= at and lowArmed and InCombat() and GetTime() - lowSaidAt >= LOW_REFIRE then
        lowArmed, lowSaidAt = false, GetTime()
        Alert(string.format(T("Your pet is low on health: %d%%. Mend Pet."), math.floor(pct + 0.5)))
    end
end

local function CheckPet()
    if not (running and isHunter and settings) then return end
    local out = HasPet()
    if out == nil then return end

    if out then
        petWasOut, noPetSaidAt = true, 0
        local dead = PetDead()
        if dead and settings.petDied and not deathSaid then
            deathSaid = true
            Alert(T("Your pet has died. Revive Pet."))
        elseif dead == false then
            deathSaid = false
        end

        HealthReminder(dead)

        local h = Happiness()
        if h and not dead then
            FeedReminder(h)
        else
            heldHappy = nil
        end
    else
        lastHappy, deathSaid, heldHappy, lowArmed = nil, false, nil, true
        HideLowWarning()
        if settings.noPet and not InCombat() and PlayerLevel() >= 10 then
            local now = GetTime()
            if now - noPetSaidAt > 300 then
                noPetSaidAt = now
                -- Not on login straight away: the pet takes a moment to come back.
                if petWasOut ~= nil then Alert(T("No pet out. Call Pet.")) end
            end
        end
        petWasOut = false
    end
    if UpdateIndicator then UpdateIndicator() end
end

